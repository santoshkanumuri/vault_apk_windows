"""Builds the sign-in provider marks: src/lib/sign-in-marks.json and the MARKS block of extension/signins.js.

Input (downloaded once, not committed):
  --icons   the unpacked `simple-icons` npm package (data/simple-icons.json, icons/*.svg),
            the same release as the built-in website icons (scripts/build-site-icons.py).

Only CC0 icons are used, as for the website icons. Simple Icons has no Microsoft, LinkedIn,
Amazon or Slack mark (their owners asked for removal), so those providers get a letter tile in
their brand color. A letter is not a logo, and a wrong or unlicensed logo is worse than a letter.
The marks only identify the sign-in method the user chose; they never decorate anything else.

Output: {"source": ..., "marks": {id: {"title", "hex", "path"} or {"title", "hex", "letter"}}}
"""
import argparse, json, os, re, sys

# Provider id -> Simple Icons slug, or None for a letter tile: (title, hex, letter).
PROVIDERS = {
    "google": "google",
    "apple": "apple",
    "microsoft": None,
    "github": "github",
    "facebook": "facebook",
    "x": "x",
    "linkedin": None,
    "discord": "discord",
    "amazon": None,
    "slack": None,
}
LETTERS = {
    "microsoft": ("Microsoft", "737373", "M"),
    "linkedin": ("LinkedIn", "0A66C2", "in"),
    "amazon": ("Amazon", "232F3E", "a"),
    "slack": ("Slack", "4A154B", "S"),
}
BLOCK = re.compile(r"(// <marks generated by scripts/build-sign-in-marks\.py>\n)(.*?)(^[ \t]*// </marks>)", re.S | re.M)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--icons", required=True)
    args = parser.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data = json.load(open(os.path.join(args.icons, "data", "simple-icons.json"), encoding="utf-8"))
    icons = data if isinstance(data, list) else data.get("icons", [])
    by_slug = {}
    for icon in icons:
        slug = icon.get("slug") or re.sub(r"[^a-z0-9]", "", icon["title"].lower())
        by_slug[slug] = icon
    version = json.load(open(os.path.join(args.icons, "package.json"), encoding="utf-8"))["version"]
    marks = {}
    for provider, slug in PROVIDERS.items():
        if slug is None:
            title, hex_color, letter = LETTERS[provider]
            marks[provider] = {"title": title, "hex": hex_color, "letter": letter}
            continue
        icon = by_slug[slug]
        if icon.get("license"):
            sys.exit(f"{slug} is not CC0: {icon['license']}")
        svg = open(os.path.join(args.icons, "icons", slug + ".svg"), encoding="utf-8").read()
        path = re.search(r'<path d="([^"]+)"', svg).group(1)
        marks[provider] = {"title": icon["title"], "hex": icon["hex"].upper(), "path": path}
    source = f"Simple Icons {version} (CC0-1.0 icons only); letter tiles for providers it does not include"
    out = {"source": source, "marks": marks}
    with open(os.path.join(root, "src", "lib", "sign-in-marks.json"), "w", encoding="utf-8", newline="\n") as file:
        file.write(json.dumps(out, indent=1) + "\n")
    script_path = os.path.join(root, "extension", "signins.js")
    script = open(script_path, encoding="utf-8").read()
    lines = [f"  // {source}."]
    lines.append("  const MARKS = {")
    for provider, mark in marks.items():
        lines.append(f"    {json.dumps(provider) if provider == 'x' else provider}: {json.dumps(mark, separators=(', ', ': '))},")
    lines.append("  };")
    replaced, count = BLOCK.subn(lambda match: match.group(1) + "\n".join(lines) + "\n" + match.group(3), script)
    if count != 1:
        sys.exit("extension/signins.js has no marks block")
    with open(script_path, "w", encoding="utf-8", newline="\n") as file:
        file.write(replaced)
    print("wrote", len(marks), "marks from", source)


if __name__ == "__main__":
    main()
