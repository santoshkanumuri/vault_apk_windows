"""Generates src/lib/networkMarks.ts from the Android app's payment-network vectors, so both apps
draw the same marks. Handles what those files use: groups with translate/scale, solid fills, and
linear gradients. Visa follows the card's text color, as on Android; the Amex blue box keeps its colors.

    python scripts/make-network-marks.py <path to card_app>

The vectors are adapted from svg-credit-card-payment-icons (Apache-2.0); the Amex blue box is the
Simple Icons `americanexpress` path (CC0-1.0); the RuPay mark is a public-domain text logo from
Wikimedia Commons. See docs/licenses/payment-icons-LICENSE.txt.
"""
import json
import pathlib
import sys
import xml.etree.ElementTree as ET

A = "{http://schemas.android.com/apk/res/android}"
AAPT = "{http://schemas.android.com/aapt}"
# Marks drawn in the card's ink color instead of their own colors (as Android tints them).
INKED = {"visa"}
# Discover and RuPay have a variant for dark cards; the light one is used when the ink is white.
FILES = {
    "visa": "network_visa", "mastercard": "network_mastercard", "amex": "network_amex",
    "discover": "network_discover", "discover-light": "network_discover_light",
    "diners": "network_diners", "jcb": "network_jcb", "unionpay": "network_unionpay",
    "rupay": "network_rupay", "rupay-light": "network_rupay_light",
}


def color(value):
    """Android #AARRGGBB / #RRGGBB to an SVG color and opacity."""
    v = value.lstrip("#")
    if len(v) == 8:
        return "#" + v[2:], int(v[:2], 16) / 255
    return "#" + v, 1.0


def convert(name, path):
    root = ET.parse(path).getroot()
    vw, vh = root.get(A + "viewportWidth"), root.get(A + "viewportHeight")
    defs, body, counter = [], [], [0]

    def walk(node, out):
        for child in node:
            tag = child.tag.split("}")[-1]
            if tag == "group":
                tx, ty = child.get(A + "translateX", "0"), child.get(A + "translateY", "0")
                sx, sy = child.get(A + "scaleX", "1"), child.get(A + "scaleY", "1")
                inner = []
                walk(child, inner)
                out.append(f'<g transform="translate({tx} {ty}) scale({sx} {sy})">' + "".join(inner) + "</g>")
            elif tag == "path":
                d = child.get(A + "pathData")
                fill_attr = ""
                gradient = child.find(f"{AAPT}attr/gradient")
                if gradient is not None:
                    counter[0] += 1
                    gid = f"nv-{name}-{counter[0]}"
                    stops = "".join(
                        f'<stop offset="{item.get(A + "offset")}" stop-color="{color(item.get(A + "color"))[0]}" stop-opacity="{color(item.get(A + "color"))[1]:.3f}"/>'
                        for item in gradient.findall("item"))
                    defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{gradient.get(A + "startX")}" y1="{gradient.get(A + "startY")}" x2="{gradient.get(A + "endX")}" y2="{gradient.get(A + "endY")}">{stops}</linearGradient>')
                    fill_attr = f' fill="url(#{gid})"'
                elif name.split("-")[0] in INKED:
                    fill_attr = ' fill="currentColor"'
                elif child.get(A + "fillColor"):
                    c, o = color(child.get(A + "fillColor"))
                    fill_attr = f' fill="{c}"' + (f' fill-opacity="{o:.3f}"' if o < 1 else "")
                out.append(f'<path d="{d}"{fill_attr}/>')

    walk(root, body)
    markup = (f"<defs>{''.join(defs)}</defs>" if defs else "") + "".join(body)
    return {"viewBox": f"0 0 {vw} {vh}", "body": markup}


def main():
    android = pathlib.Path(sys.argv[1]) / "app/src/main/res/drawable"
    marks = {key: convert(key, android / f"{file}.xml") for key, file in FILES.items()}
    out = pathlib.Path(__file__).resolve().parent.parent / "src/lib/networkMarks.ts"
    out.write_text(
        "// GENERATED by scripts/make-network-marks.py from the Android app's network vectors. Do not edit.\n"
        "// Adapted from svg-credit-card-payment-icons (Apache-2.0); Amex is from Simple Icons (CC0-1.0);\n"
        "// RuPay is a public-domain text logo.\n"
        "// Network names and logos identify stored cards; they do not imply affiliation or endorsement.\n"
        "export type NetworkMark = { viewBox: string; body: string };\n"
        f"export const NETWORK_MARKS: Record<string, NetworkMark> = {json.dumps(marks, indent=2)};\n",
        encoding="utf-8", newline="\n")
    print("wrote", out, {k: len(v["body"]) for k, v in marks.items()})


if __name__ == "__main__":
    main()
